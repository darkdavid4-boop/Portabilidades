CREATE TABLE registros_telecomunicaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mes VARCHAR(7),
    pais VARCHAR(100),
    servicio VARCHAR(150),
    concepto VARCHAR(100),
    operador VARCHAR(150),
    segmento VARCHAR(150),
    tecnologia_acceso VARCHAR(150),
    contrato VARCHAR(150),
    terminal_telefonia_movil VARCHAR(150),
    linea_ba_movil VARCHAR(150),
    tipo_ba_mayorista VARCHAR(150),
    tipo_portabilidad VARCHAR(50),
    unidades VARCHAR(50),
    lineas BIGINT,
    tasa_penetracion DOUBLE PRECISION,
    portabilidades BIGINT
);

CREATE INDEX idx_registros_mes ON registros_telecomunicaciones (mes);
CREATE INDEX idx_registros_operador_mes ON registros_telecomunicaciones (operador, mes);
CREATE INDEX idx_registros_servicio_mes ON registros_telecomunicaciones (servicio, mes);

CREATE TABLE dataset_import (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    checksum VARCHAR(64) NOT NULL,
    row_count INTEGER NOT NULL,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
